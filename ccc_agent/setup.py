def assets_dir():
    """On-disk path to the bundled shell assets (real files in a wheel install)."""
    return str(resources.files("ccc_agent").joinpath("assets"))


def plugins_dir():
    """On-disk path to bundled agent integration assets.

    Codex assets are mounted read-only into its plugin-cache path for contained
    sessions. Setup materializes Claude's complete seed from these packaged
    assets; contained runs point Claude at it with
    ``CLAUDE_CODE_PLUGIN_SEED_DIR``. Hermes assets remain packaged for explicit
    operator use but are not injected by default.
    """
    return os.path.join(assets_dir(), "plugins")


def _make_executable(path):
    try:
        mode = os.stat(path).st_mode
        os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass


def _resolve(name, override=None, fallbacks=()):
    if override:
        return override
    found = which(name)
    if found:
        return found
    for cand in fallbacks:
        if cand and os.path.exists(cand):
            return cand
    return name  # bare name: resolved on PATH at runtime


def _resolve_branchfs(override=None):
    if override:
        return override
    bundled = branchfs_runtime.packaged_branchfs_bin()
    if bundled:
        return bundled
    return _resolve("branchfs", None, ["/usr/local/bin/branchfs"])


def _warn_branchfs_runtime(binary):
    packaged = branchfs_runtime.is_packaged_branchfs_bin(binary)
    if packaged:
        ok, detail = branchfs_runtime.libfuse3_status()
        if not ok:
            sys.stderr.write(
                "ccc-agent setup: WARNING packaged BranchFS requires libfuse3 "
                "at runtime; install the system libfuse3 package (details: %s)\n"
                % detail)
        version = branchfs_runtime.packaged_branchfs_version()
    else:
        version = branchfs_runtime.probe_branchfs_version(binary)
    expected = branchfs_runtime.EXPECTED_BRANCHFS_VERSION
    if version and version != expected:
        sys.stderr.write(
            "ccc-agent setup: WARNING BranchFS version %s was found, but "
            "ccc-agent expects vicoslab BranchFS %s. Install "
            "ccc-agent[branchfs] or pass --branchfs-bin for the matching "
            "vicoslab/branchfs release.\n" % (version, expected))
    elif version is None and not packaged and binary != "branchfs":
        sys.stderr.write(
            "ccc-agent setup: WARNING could not verify BranchFS version for "
            "%s; ccc-agent expects vicoslab BranchFS %s. Install "
            "ccc-agent[branchfs] to use the pinned GitHub release binary.\n"
            % (binary, expected))


def _write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(data, fh, indent=2)
    os.chmod(path, 0o644)


def _shell_single_quote(value):
    """Quote a string for POSIX shell single-quoted assignment."""
    return "'" + value.replace("'", "'\"'\"'") + "'"


def shim_path_hook_content(shim_dir):
    """Sourceable POSIX shell snippet that keeps the shim dir first on PATH."""
    quoted = _shell_single_quote(os.path.abspath(shim_dir))
    return ("#!/bin/sh\n"
            "# Generated by ccc-agent setup. Source from shell startup files to\n"
            "# keep transparent ccc-agent shims ahead of user/conda installs.\n"
            "_CCC_AGENT_SHIM_DIR=%s\n"
            "if [ -d \"$_CCC_AGENT_SHIM_DIR\" ]; then\n"
            "    _CCC_AGENT_OLD_IFS=$IFS\n"
            "    IFS=:; _CCC_AGENT_PATH=\n"
            "    for _CCC_AGENT_PART in $PATH; do\n"
            "        [ \"$_CCC_AGENT_PART\" = \"$_CCC_AGENT_SHIM_DIR\" ] && continue\n"
            "        if [ -z \"$_CCC_AGENT_PATH\" ]; then\n"
            "            _CCC_AGENT_PATH=$_CCC_AGENT_PART\n"
            "        else\n"
            "            _CCC_AGENT_PATH=$_CCC_AGENT_PATH:$_CCC_AGENT_PART\n"
            "        fi\n"
            "    done\n"
            "    IFS=$_CCC_AGENT_OLD_IFS\n"
            "    PATH=$_CCC_AGENT_SHIM_DIR${_CCC_AGENT_PATH:+:$_CCC_AGENT_PATH}\n"
            "    export PATH\n"
            "    export CCC_AGENT_SHIM_DIR=\"$_CCC_AGENT_SHIM_DIR\"\n"
            "    unset _CCC_AGENT_PATH _CCC_AGENT_PART _CCC_AGENT_OLD_IFS\n"
            "fi\n"
            "unset _CCC_AGENT_SHIM_DIR\n" % quoted)


def write_shell_path_hook(path, shim_dir):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(shim_path_hook_content(shim_dir))
    os.chmod(path, 0o644)
    return path


def write_conda_shim_hooks(conda_prefix, shim_dir):
    """Install env-specific conda hooks that keep ccc shims first on PATH.

    Conda activation normally prepends ``$CONDA_PREFIX/bin``. If the ccc shims
    only live in /usr/local/bin, a conda-installed ``codex``/``claude`` wins and
    bypasses containment. These hooks run after conda's PATH mutation and
    re-prepend a trusted shim directory; the shim redirects to ``ccc-agent run``
    and passes an unshimmed PATH so the contained command resolves the active
    env's real binary normally.
    """
    activate_dir = os.path.join(conda_prefix, "etc", "conda", "activate.d")
    deactivate_dir = os.path.join(conda_prefix, "etc", "conda", "deactivate.d")
    os.makedirs(activate_dir, exist_ok=True)
    os.makedirs(deactivate_dir, exist_ok=True)
    quoted = _shell_single_quote(os.path.abspath(shim_dir))
    activate = os.path.join(activate_dir, "ccc-agent-shims.sh")
    deactivate = os.path.join(deactivate_dir, "ccc-agent-shims.sh")
    with open(activate, "w") as fh:
        fh.write("#!/bin/sh\n"
                 "# Generated by ccc-agent setup. Keep containment shims ahead\n"
                 "# of $CONDA_PREFIX/bin so conda-installed agents are wrapped.\n"
                 "_CCC_AGENT_SHIM_DIR=%s\n"
                 "case \"$PATH\" in\n"
                 "    \"$_CCC_AGENT_SHIM_DIR\"|\"$_CCC_AGENT_SHIM_DIR\":*) ;;\n"
                 "    *) PATH=\"$_CCC_AGENT_SHIM_DIR:$PATH\" ;;\n"
                 "esac\n"
                 "export PATH\n"
                 "export CCC_AGENT_SHIM_DIR=\"$_CCC_AGENT_SHIM_DIR\"\n"
                 "unset _CCC_AGENT_SHIM_DIR\n" % quoted)
    with open(deactivate, "w") as fh:
        fh.write("#!/bin/sh\n"
                 "# Generated by ccc-agent setup. Remove the leading shim path\n"
                 "# this env's activate hook prepended.\n"
                 "_CCC_AGENT_SHIM_DIR=%s\n"
                 "case \"$PATH\" in\n"
                 "    \"$_CCC_AGENT_SHIM_DIR\") PATH=\"\" ;;\n"
                 "    \"$_CCC_AGENT_SHIM_DIR\":*) PATH=${PATH#\"$_CCC_AGENT_SHIM_DIR\":} ;;\n"
                 "esac\n"
                 "export PATH\n"
                 "unset CCC_AGENT_SHIM_DIR\n"
                 "unset _CCC_AGENT_SHIM_DIR\n" % quoted)
    os.chmod(activate, 0o755)
    os.chmod(deactivate, 0o755)
    return activate, deactivate


